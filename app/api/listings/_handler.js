function validateTitleDesc(title, description) {
  const L = LIMITS.listing;
  const cleanTitle = (title || '').trim();
  const cleanDesc  = (description || '').trim();

  if (cleanTitle.length < L.titleMinLength || cleanTitle.length > L.titleMaxLength) {
    throw new ApiError(
      `Title must be between ${L.titleMinLength} and ${L.titleMaxLength} characters.`,
      'TITLE_LENGTH', 400
    );
  }
  if (cleanDesc.length < L.descMinLength || cleanDesc.length > L.descMaxLength) {
    throw new ApiError(
      `Description must be between ${L.descMinLength} and ${L.descMaxLength} characters.`,
      'DESC_LENGTH', 400
    );
  }
  return { cleanTitle, cleanDesc };
}

function validateUrlIfWebsite(type, isTemplate, url) {
  if (type === 'website' && !isTemplate) {
    if (!url || !/^https?:\/\/.+/.test(url)) {
      throw new ApiError('Please provide a valid URL starting with https://.', 'INVALID_URL', 400);
    }
  }
}

// 3D Asset listings have no uploaded screenshots — the "preview" IS a live
// embedded iframe (Sketchfab or any other platform's embed), so a valid
// embed URL is required in its place. Mirrors lib/embedUrl.ts's
// extractIframeSrc/isValidEmbedUrl exactly — duplicated rather than shared
// because this file is plain CommonJS with no import from the Next.js
// app's lib/ tree (see every other helper below, which is likewise
// self-contained). Re-validated here regardless of what the client already
// checked, same principle as every other field in this handler: the
// client-side check is a UX nicety, this one is the actual gate.
function extractEmbedSrc(snippet) {
  const match = String(snippet).match(/\bsrc\s*=\s*["']([^"']+)["']/i);
  return match ? match[1].trim() : null;
}
function isValidEmbedUrl(value) {
  const v = String(value).trim();
  if (!v) return false;
  try {
    const u = new URL(v);
    return u.protocol === 'http:' || u.protocol === 'https:';
  } catch {
    return false;
  }
}
// `raw` may be a bare URL or a full <iframe> snippet — try direct URL
// validation first, then fall back to extracting src= from it, so this one
// function covers both input modes the form offers without the client
// having to tell the server which mode was used.
function resolveEmbedUrl(raw) {
  if (!raw) return null;
  const direct = String(raw).trim();
  if (isValidEmbedUrl(direct)) return direct;
  const extracted = extractEmbedSrc(direct);
  if (extracted && isValidEmbedUrl(extracted)) return extracted;
  return null;
}
function validateEmbedIf3d(type, embedCode) {
  if (type !== '3d') return null;
  const resolved = resolveEmbedUrl(embedCode);
  if (!resolved) {
    throw new ApiError(
      'Please provide a valid embed link or iframe code for your 3D asset preview.',
      'INVALID_EMBED_URL', 400
    );
  }
  return resolved;
}

// Builds the nested sub-objects (financials/tech/settings/platforms) shared
// between create and update, from whatever subset of fields was sent.
function buildFinancials(financials) {
  if (!financials || typeof financials !== 'object') return null;
  const rev = Number.isFinite(financials.revenue)  ? financials.revenue  : null;
  const exp = Number.isFinite(financials.expenses) ? financials.expenses : null;
  const out = {
    price:    Number.isFinite(financials.price) ? financials.price : null,
    revenue:  rev,
    expenses: exp,
    profit:   (rev !== null && exp !== null) ? rev - exp : null,
  };
  if (financials.monetizationModel) out.monetizationModel = String(financials.monetizationModel).slice(0, 60);
  if (Number.isFinite(financials.subscriptionPriceMonthly)) out.subscriptionPriceMonthly = financials.subscriptionPriceMonthly;
  if (Number.isFinite(financials.subscriptionPriceAnnual))  out.subscriptionPriceAnnual  = financials.subscriptionPriceAnnual;
  return out;
}

// Minimum bid increment, platform-wide, not seller-configurable — mirrors
// MIN_BID_INCREMENT_PCT in lib/listings.ts (that copy is display-only; this
// is the value actually enforced). 10% means: with no bids yet, the first
// bid must be >= startPrice * 1.10; with a standing bid, the next bid must
// be >= currentBid * 1.10. There is no "meet the exact current bid" or
// flat-increment path — every bid clears the prior figure by at least 10%.
const MIN_BID_INCREMENT_PCT = 0.10;

// Auction listings must run at least this long — guards against a seller
// setting start === end (or end a few seconds after start) to dodge real
// bidding while still showing an "auction" badge.
const MIN_AUCTION_DURATION_MS = 60 * 60 * 1000; // 1 hour
const MAX_AUCTION_DURATION_MS = 30 * 24 * 60 * 60 * 1000; // 30 days

// Validates + normalizes the `auction` payload for listing.create /
// listing.update. Returns null when saleType isn't "auction" (caller then
// falls back to ordinary financials.price / fixed-sale behavior).
// Deliberately strict — this is the one place a seller's start/end/price
// choices become the numbers `handleBid`'s transaction will enforce, so a
// loosely-validated auction here means an exploitable one later.
function buildAuction(saleType, auction, existing) {
  if (saleType !== 'auction') return null;
  if (!auction || typeof auction !== 'object') {
    throw new ApiError('Auction start time, end time, and starting price are required.', 'INVALID_AUCTION', 400);
  }

  const startPrice = Number(auction.startPrice);
  if (!Number.isFinite(startPrice) || startPrice <= 0) {
    throw new ApiError('Starting price must be a positive number.', 'INVALID_AUCTION_PRICE', 400);
  }

  const startMs = Date.parse(auction.startTime);
  const endMs   = Date.parse(auction.endTime);
  if (!Number.isFinite(startMs) || !Number.isFinite(endMs)) {
    throw new ApiError('Auction start and end time must be valid dates.', 'INVALID_AUCTION_DATES', 400);
  }
  if (endMs <= startMs) {
    throw new ApiError('Auction end time must be after the start time.', 'INVALID_AUCTION_RANGE', 400);
  }
  if (endMs - startMs < MIN_AUCTION_DURATION_MS) {
    throw new ApiError('Auctions must run for at least 1 hour.', 'AUCTION_TOO_SHORT', 400);
  }
  if (endMs - startMs > MAX_AUCTION_DURATION_MS) {
    throw new ApiError('Auctions can run for at most 30 days.', 'AUCTION_TOO_LONG', 400);
  }

  // Editing an auction that already has bids: the seller can no longer
  // move the goalposts on price/start — that would be unfair to bidders
  // who already committed against the original terms. End time is also
  // locked once live (sellers shouldn't be able to cut an auction short
  // right as they're about to lose, or extend one right as they're about
  // to win as a buyer using a second account — extension logic, if ever
  // added, belongs in the bid-placement path, not a seller-initiated edit).
  if (existing && existing.auction && (existing.auction.bidCount || 0) > 0) {
    throw new ApiError(
      'This auction already has bids — its price, start time, and end time can no longer be changed.',
      'AUCTION_HAS_BIDS', 409
    );
  }

  const nowMs = Date.now();
  return {
    startPrice,
    startTime: new Date(startMs).toISOString(),
    endTime:   new Date(endMs).toISOString(),
    currentBid: existing?.auction?.currentBid ?? null,
    currentBidderId: existing?.auction?.currentBidderId ?? null,
    currentBidderHandle: existing?.auction?.currentBidderHandle ?? null,
    bidCount: existing?.auction?.bidCount ?? 0,
    status: endMs <= nowMs ? 'ended' : (startMs > nowMs ? 'scheduled' : 'live'),
    winnerId: existing?.auction?.winnerId ?? null,
  };
}


