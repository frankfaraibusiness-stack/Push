// ── Firebase ID token verification via REST ──────────────────────────────────
// Firebase Web API key — used server-side only to call Identity Toolkit's
// accounts:lookup REST endpoint for ID token verification. Same public-by-
// design value as lib/firebase.ts's client config (see that file's own
// comment), but still read from env so a fresh Firebase project/account
// only requires updating .env, never a code change.
const FIREBASE_WEB_API_KEY = process.env.NEXT_PUBLIC_FIREBASE_API_KEY;
if (!FIREBASE_WEB_API_KEY) {
  throw new Error('NEXT_PUBLIC_FIREBASE_API_KEY is not set — required for Firebase ID token verification.');
}

async function verifyFirebaseToken(idToken) {
  const res = await fetch(
    `https://identitytoolkit.googleapis.com/v1/accounts:lookup?key=${FIREBASE_WEB_API_KEY}`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ idToken }),
    }
  );
  if (!res.ok) throw new ApiError('Invalid Firebase token', 'AUTH_INVALID', 401);
  const data = await res.json();
  const user = data.users?.[0];
  if (!user) throw new ApiError('User not found', 'AUTH_USER_NOT_FOUND', 401);
  return user; // { localId, email, ... }
}

// ── Typed API error — carries a machine-readable code alongside the message ─
class ApiError extends Error {
  constructor(message, code = 'INTERNAL', statusCode = 500) {
    super(message);
    this.code = code;
    this.statusCode = statusCode;
  }
}

function ok(res, data = {}, statusCode = 200) {
  return res.status(statusCode).json({ ok: true, data });
}
function fail(res, err) {
  const statusCode = err.statusCode || 500;
  const code = err.code || 'INTERNAL';
  const message = err.message || 'Internal error';
  return res.status(statusCode).json({ ok: false, error: { message, code } });
}

